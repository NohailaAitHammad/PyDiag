def moyenne_groupe(etudiants):
    total_moyennes = 0
    nombre_etudiants = 0

    for etudiant in etudiants:
        if etudiant['notes']:
            total_moyennes += calculer_moyenne(etudiant['notes'])
            nombre_etudiants += 1

    if nombre_etudiants == 0:
        return 0

    return total_moyennes / nombre_etudiants



