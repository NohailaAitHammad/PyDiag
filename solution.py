def fusionner_groupes(groupe1, groupe2):
    groupe_fusionne = dict(groupe1)
    conflits = []

    for nom, data2 in groupe2.items():
        if nom in groupe_fusionne:
            conflits.append(f"Conflit pour {nom}: les données de groupe_b ne sont pas fusionnées pour éviter l'écrasement. Données de groupe_a conservées.")
        else:
            groupe_fusionne[nom] = data2

    return groupe_fusionne, conflits

